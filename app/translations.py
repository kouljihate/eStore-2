def get_translation(lang, key):
    translations = TRANSLATIONS.get(lang, TRANSLATIONS["ar"])
    value = translations.get(key)
    if value is not None:
        return value
    value = TRANSLATIONS["ar"].get(key)
    if value is not None:
        return value
    return key


def t(page, key):
    return get_translation(page.session.store.get("lang") or "ar", key)


# Stored transaction categories are English ("Sale", "Credit", "General").
# Translate them on display; unknown/custom values pass through unchanged.
_TX_CAT_KEYS = {
    "sale": "cat_sale",
    "credit": "cat_credit",
    "general": "category_general",
}


def tx_category_label(page, category):
    key = _TX_CAT_KEYS.get((category or "").strip().lower())
    if key:
        return t(page, key)
    return category or ""